// 1 путь, 2 пути, 5 путей
function plural(n: number, one: string, few: string, many: string) {
  const a = n % 10,
    b = n % 100;
  if (a === 1 && b !== 11) return one;
  if (a >= 2 && a <= 4 && (b < 12 || b > 14)) return few;
  return many;
}

